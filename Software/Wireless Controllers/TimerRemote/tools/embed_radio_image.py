#!/usr/bin/env python3
"""Regenerates include/radio_image.h from the RA-08H P2P bridge binary.

Run after rebuilding Software/RA08H_p2p_bridge/p2p_bridge.bin:
    python tools/embed_radio_image.py
The remote embeds this image so it can flash an unprogrammed RA-08H itself
(see src/radioFlash.cpp).
"""
import pathlib, zlib

here = pathlib.Path(__file__).resolve().parent.parent
src = here.parent.parent / "RA08H_p2p_bridge" / "p2p_bridge.bin"
dst = here / "include" / "radio_image.h"

data = src.read_bytes()
crc = zlib.crc32(data) & 0xFFFFFFFF
lines = []
for i in range(0, len(data), 16):
    lines.append("    " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",")

dst.write_text(
    "// GENERATED by tools/embed_radio_image.py from Software/RA08H_p2p_bridge/p2p_bridge.bin\n"
    "// Do not edit by hand.\n"
    "#ifndef RADIO_IMAGE_H\n#define RADIO_IMAGE_H\n\n#include <stdint.h>\n\n"
    "#define RADIO_IMAGE_LEN %du\n"
    "#define RADIO_IMAGE_CRC32 0x%08Xu\n"
    "#define RADIO_IMAGE_FLASH_ADDR 0x08000000u\n\n"
    "static const uint8_t RADIO_IMAGE[RADIO_IMAGE_LEN] = {\n%s\n};\n\n#endif\n"
    % (len(data), crc, "\n".join(lines))
)
print("wrote", dst, len(data), "bytes, crc32 0x%08X" % crc)
